**2026年8月23日至29日**，由课题组组织的**“天体测量、天文参考系与地球自转——微角秒时代的新挑战”暑期学校暨学术研讨会**在南京举行。

本次活动由**南京大学天文与空间科学学院主办**，得到**中国天文学会天体测量专业委员会和江苏省天文学会支持**。来自中国科学院紫金山天文台、上海天文台、云南天文台、国家授时中心、国家天文台以及南京大学、暨南大学、云南大学、北京大学、北京师范大学等高校和科研院所的百余名专家学者、青年科研人员和研究生参会。

## 会议背景与议题

随着Gaia空间天体测量任务、甚长基线干涉测量（VLBI）和激光测距等观测技术的发展，微角秒精度观测对天文参考系的构建与维持、理论模型和数据处理方法提出了更高要求。

本次活动采用“暑期学校＋学术研讨会”的形式，将基础培训与前沿研究交流相结合，主要议题包括：

- 高精度天体测量。
- 天球参考系与参考架。
- 地球自转模型与地球定向参数。
- 时间尺度。
- 太阳系历表。
- 基本天文学应用。

## 暑期学校

**8月24日至26日**，为期三天的暑期学校围绕天体测量、天文参考系与地球自转研究的基本理论、观测技术和数据处理方法展开。

来自相关高校和科研院所的专家开展专题授课，并指导学员进行实践训练。课程将理论模型与实际观测、计算和科学应用相联系，帮助学生和青年学者系统了解研究方法，并通过课堂讨论与实践交流加深理解。

## 学术研讨会

**8月27日上午**，学术研讨会正式开幕。开幕式由**刘佳成老师**主持，南京大学天文与空间科学学院院长**李向东教授**、中国科学院上海天文台台长**孔大力研究员**、中国科学院云南天文台副台长**李语强研究员**分别致辞。

开幕式上，与会师生向南京大学天文与空间科学学院荣休教师**朱紫老师**献花，感谢其长期以来在天体测量学科建设、人才培养和学术交流中的贡献。

为期两天的学术研讨围绕三个专题展开：

- **地月系统与空间动力学。**
- **VLBI、射电观测与天球参考架。**
- **空间探测、星表与高精度天体测量。**

会议将系统课程、实践训练与学术报告相结合，为青年学生了解学科前沿、交流研究方法提供了平台，也加强了国内相关高校和科研院所之间的联系与合作。

