Our group organized the summer school and workshop **“Astrometry, Astronomical Reference Systems and Earth Rotation: New Challenges in the Microarcsecond Era”**, held in **Nanjing on 23–29 August 2026**.

Hosted by the **School of Astronomy and Space Science, Nanjing University**, with support from the **Astrometry Committee of the Chinese Astronomical Society** and the **Jiangsu Astronomical Society**, the event brought together more than 100 researchers, early-career scientists, and postgraduate students from universities and research institutes across China.

## Scientific scope

Advances in Gaia space astrometry, very long baseline interferometry (VLBI), and laser ranging are placing increasingly stringent demands on astronomical reference systems, theoretical models, and data analysis. The event combined foundational training with discussions of current research and the challenges of microarcsecond astrometry.

The scientific scope included:

- High-precision astrometry.
- Celestial reference systems and frames.
- Earth-rotation models and Earth orientation parameters.
- Time scales.
- Solar-system ephemerides.
- Applications of fundamental astronomy.

## Summer school

The three-day summer school, held on **24–26 August**, introduced the fundamental theories, observational techniques, and data-processing methods used in astrometry, astronomical reference systems, and Earth-rotation research.

Specialist lectures were accompanied by practical exercises, connecting theoretical models with observations, computation, and scientific applications. The programme provided students and early-career researchers with opportunities to discuss methods and research questions directly with the lecturers.

## Research workshop

The workshop opened on the morning of **27 August**, with **Jia-Cheng Liu** chairing the opening session. **Xiangdong Li**, Dean of the School of Astronomy and Space Science at Nanjing University, **Dali Kong**, Director of Shanghai Astronomical Observatory, and **Yuqiang Li**, Deputy Director of Yunnan Observatories, delivered opening remarks.

Participants also honoured **Prof. Zi Zhu** for his longstanding contributions to astrometry research, education, and academic exchange.

The two-day scientific programme focused on three themes:

- **The Earth–Moon system and space dynamics.**
- **VLBI, radio observations, and celestial reference frames.**
- **Space exploration, catalogues, and high-precision astrometry.**

By combining lectures, practical training, and research presentations, the event supported exchanges between institutions and provided a forum for developing future collaborations.

